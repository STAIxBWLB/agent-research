import { isVerified, type Candidate } from "./candidates.ts";

const STOP = new Set(["the", "a", "an", "on", "of", "for", "and", "in", "to", "with", "towards", "toward", "from", "via", "by", "at", "is", "are"]);
const ascii = (text: string) => text.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^A-Za-z]/g, "").toLowerCase();

/** "Family, Given" stays; "Given Family" becomes "Family, Given". */
export function bibName(name: string): string {
  if (name.includes(",")) return name.trim();
  const parts = name.trim().split(/\s+/);
  return parts.length < 2 ? parts[0] ?? "" : `${parts.at(-1)}, ${parts.slice(0, -1).join(" ")}`;
}

export function baseKey(c: Candidate): string {
  const meta = c.verify?.registry, first = (meta?.authors ?? c.authors)[0];
  const family = first ? ascii(bibName(first).split(",")[0]!) : "";
  const year = meta?.year ?? c.year;
  const word = (meta?.title ?? c.title).split(/\s+/).map(ascii).find(w => w.length >= 3 && !STOP.has(w)) ?? "";
  const key = `${family}${year ?? ""}${word}`;
  return /[a-z]/.test(key) ? key : `ref${year ?? ""}`;
}

/** Assign keys once, in id order, with a, b, ... suffixes on collision. Assigned keys never change. */
export function assignCitekeys(list: Candidate[], eligible: Candidate[]): number {
  const taken = new Set(list.map(c => c.citekey).filter((k): k is string => !!k));
  let assigned = 0;
  for (const c of [...eligible].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    if (c.citekey) continue;
    const base = baseKey(c);
    let key = base;
    for (let n = 0; taken.has(key); n++) key = `${base}${n < 26 ? String.fromCharCode(97 + n) : n}`;
    c.citekey = key; taken.add(key); assigned++;
  }
  return assigned;
}

export function escapeBib(text: string): string {
  // A private-use placeholder keeps the backslash replacement from being escaped again.
  return text.replace(/\uE000/g, "").replace(/\\/g, "\uE000").replace(/([{}&%$#_])/g, "\\$1").replace(/~/g, "\\textasciitilde{}").replace(/\^/g, "\\textasciicircum{}").replace(/\uE000/g, "\\textbackslash{}");
}

export function bibEntry(c: Candidate): string {
  const meta = c.verify?.registry, type = meta?.type ?? "";
  const kind = type === "journal-article" ? "article" : type === "proceedings-article" ? "inproceedings" : "misc";
  const fields: [string, string][] = [];
  const authors = meta?.authors.length ? meta.authors : c.authors;
  if (authors.length) fields.push(["author", authors.map(a => escapeBib(bibName(a))).join(" and ")]);
  fields.push(["title", `{${escapeBib(meta?.title ?? c.title)}}`]);
  const year = meta?.year ?? c.year;
  if (year !== undefined) fields.push(["year", String(year)]);
  const venue = meta?.venue ?? c.venue;
  if (venue) fields.push([kind === "article" ? "journal" : kind === "inproceedings" ? "booktitle" : "publisher", escapeBib(venue)]);
  if (c.doi) fields.push(["doi", escapeBib(c.doi)]);
  if (c.arxivId) { fields.push(["eprint", escapeBib(c.arxivId)], ["archiveprefix", "arXiv"]); if (!c.doi) fields.push(["url", `https://arxiv.org/abs/${c.arxivId}`]); }
  return `@${kind}{${c.citekey},\n${fields.map(([k, v]) => `  ${k} = {${v}}`).join(",\n")}\n}\n`;
}

/** Only included and verified candidates are written. */
export function renderBib(list: Candidate[]): { text: string; entries: number } {
  const eligible = list.filter(c => c.status === "included" && isVerified(c) && c.citekey).sort((a, b) => (a.citekey! < b.citekey! ? -1 : 1));
  return { text: `% Generated by ares (agent-research). Do not edit: rerun ares lit bib.\n\n${eligible.map(bibEntry).join("\n")}`, entries: eligible.length };
}
